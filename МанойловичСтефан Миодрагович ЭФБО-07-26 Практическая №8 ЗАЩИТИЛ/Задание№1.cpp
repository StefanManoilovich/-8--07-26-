#include <iostream> // Подключаем библиотеку для ввода данных и вывода результатов на экран.
using namespace std; // Позволяет писать cout и cin без std:: перед ними.

// Создаём функцию быстрого возведения числа в степень.
// a — число, которое нужно возвести в степень.
// n — показатель степени, в которую нужно возвести число a.
long long power(long long a, int n) { // Объявляем функцию, которая возвращает целое число типа long long.

    long long result = 1; // Создаём переменную для результата и изначально записываем в неё 1.

    while (n > 0) { // Повторяем цикл, пока показатель степени больше нуля.

        if (n % 2 == 1) { // Проверяем, является ли показатель степени нечётным.
            result *= a; // Если степень нечётная, умножаем результат на текущее основание a.
        } // Завершаем проверку на нечётность.

        a *= a; // Возводим основание в квадрат, чтобы быстрее вычислять большую степень.
        n /= 2; // Делим показатель степени на 2, отбрасывая дробную часть.
    } // Завершаем цикл, когда показатель степени становится равным нулю.

    return result; // Возвращаем вычисленный результат из функции.
} // Завершаем функцию быстрого возведения в степень.

int main() { // Главная функция, с которой начинается выполнение программы.

    long long a; // Объявляем переменную для числа, которое будем возводить в степень.
    int n; // Объявляем переменную для показателя степени.

    cout << "Введите число: "; // Просим пользователя ввести основание степени.
    cin >> a; // Считываем основание степени с клавиатуры.

    cout << "Введите степень: "; // Просим пользователя ввести показатель степени.
    cin >> n; // Считываем показатель степени с клавиатуры.

    cout << "Результат: " << power(a, n) << endl; // Вызываем функцию power и выводим результат вычисления.

    return 0; // Завершаем программу, сообщая, что она выполнилась успешно.
} // Завершаем главную функцию программы.