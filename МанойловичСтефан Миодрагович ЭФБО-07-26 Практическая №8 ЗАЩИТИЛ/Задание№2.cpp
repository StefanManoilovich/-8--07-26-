#include <iostream> // Подключаем библиотеку для ввода и вывода данных.
using namespace std; // Позволяет использовать cin и cout без std::.

// Создаём рекурсивную функцию для нахождения НОД двух чисел.
// a и b — два натуральных числа, для которых нужно найти НОД.
int nod(int a, int b) { // Объявляем функцию nod, которая возвращает целое число.

    if (b == 0) { // Проверяем, равно ли второе число нулю.
        return a; // Если b равно 0, возвращаем a — это и есть НОД.
    } // Завершаем проверку условия выхода из рекурсии.

    return nod(b, a % b); // Вызываем функцию повторно: передаём b и остаток от деления a на b.
} // Завершаем функцию nod.

int main() { // Главная функция, с которой начинается выполнение программы.

    int a, b; // Объявляем две переменные для хранения введённых чисел.

    cin >> a >> b; // Считываем два числа с клавиатуры.

    cout << nod(a, b) << endl; // Вызываем функцию nod и выводим найденный НОД на экран.

    return 0; // Завершаем программу.
} // Завершаем главную функцию.