#include <iostream> // Подключаем библиотеку для вывода текста на экран.
using namespace std; // Позволяет использовать cout без std::.

// Создаём рекурсивную функцию для перекладывания ингредиентов.
// n — количество ингредиентов, которые нужно переложить.
// from — номер салфетки, с которой перекладываем ингредиенты.
// to — номер салфетки, на которую перекладываем ингредиенты.
// help — номер вспомогательной салфетки.
void moveIngredients(int n, int from, int to, int help) {

    if (n == 1) { // Если остался только один ингредиент, его можно переложить сразу.
        cout << "Ingredient 1 move from " << from << " to " << to << endl; // Выводим инструкцию для перемещения одного ингредиента.
        return; // Завершаем текущий вызов функции.
    } // Завершаем проверку базового случая рекурсии.

    moveIngredients(n - 1, from, help, to); // Сначала перекладываем n-1 меньших ингредиентов на вспомогательную салфетку.

    cout << "Ingredient " << n << " move from " << from << " to " << to << endl; // Перекладываем самый большой из оставшихся ингредиентов на целевую салфетку.

    moveIngredients(n - 1, help, to, from); // Затем перекладываем n-1 ингредиентов со вспомогательной салфетки на целевую.
} // Завершаем функцию перемещения ингредиентов.

int main() { // Главная функция программы, с которой начинается выполнение.

    int n; // Объявляем переменную для количества ингредиентов.
    cin >> n; // Считываем количество ингредиентов с клавиатуры.

    moveIngredients(n, 1, 3, 2); // Перекладываем все ингредиенты с салфетки 1 на салфетку 3, используя салфетку 2 как вспомогательную.

    return 0; // Завершаем программу.
} // Завершаем главную функцию.